#!/usr/bin/env python
"""Generate the AMD-derived data headers for the D3D12 DLL from your copy of the FSR4 source.

Writes two headers into src/dll/ (both are git-ignored; they are never committed):

  fsr4_initializer_blob.h   initializers.bin of each INT8 preset, as C++ byte arrays
  fsr4_encoder1_weights.h   encoder1 conv weights (cbPass_Weights, 256 dwords) of each
                            preset, parsed from that preset's pre.hlsl

Usage:
    python scripts/embed_initializer.py --fsr4-source <path-to-FidelityFX-SDK-checkout>

The FSR4 source root can also be given via the FSR4_SOURCE environment variable.
It is the directory that contains Kits/FidelityFX/upscalers/fsr4.
"""

import argparse
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SHADER_SUBDIR = Path("Kits/FidelityFX/upscalers/fsr4/internal/shaders")

PRESETS = [
    ("quality",     "fsr4_model_v07_i8_quality"),
    ("balanced",    "fsr4_model_v07_i8_balanced"),
    ("performance", "fsr4_model_v07_i8_performance"),
    ("ultraperf",   "fsr4_model_v07_i8_ultraperf"),
]

ENCODER1_ARRAY = "embedded_encoder1_DownscaleStridedConv2x2_downscale_conv_weight_dwords"


def embed_blob(out, data, var_name, label):
    size = len(data)
    out.write(f"// {label} ({size} bytes)\n")
    out.write(f"static const uint8_t {var_name}[] = {{\n")

    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        out.write(f"    {hex_str},\n")

    out.write(f"}};\n\n")
    return size


def read_encoder1_weights(pre_hlsl: Path):
    text = pre_hlsl.read_text()
    m = re.search(re.escape(ENCODER1_ARRAY) + r"\[(\d+)\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"ERROR: {ENCODER1_ARRAY} not found in {pre_hlsl}")
    body = re.sub(r"//[^\n]*", "", m.group(2))
    vals = re.findall(r"0x[0-9a-fA-F]+", body)
    if len(vals) != 256 or int(m.group(1)) != 256:
        sys.exit(f"ERROR: expected 256 dwords in {pre_hlsl}, found {len(vals)}")
    return vals


def write_initializer_header(shader_base: Path, output_file: Path):
    with open(output_file, "w") as out:
        out.write("// Auto-generated by scripts/embed_initializer.py -- do not edit, do not commit.\n")
        out.write("// Derived from AMD FidelityFX SDK FSR4 source (MIT License,\n")
        out.write("// Copyright (C) 2025 Advanced Micro Devices, Inc.). See LICENSE.\n")
        out.write("// Contains initializer data for all quality presets\n")
        out.write("#pragma once\n\n")
        out.write("#include <cstdint>\n\n")

        sizes = []
        for preset_name, preset_dir in PRESETS:
            init_path = shader_base / preset_dir / "initializers.bin"
            data = init_path.read_bytes()
            size = embed_blob(out, data, f"g_initializer_{preset_name}_data",
                              f"{preset_dir}/initializers.bin")
            sizes.append((preset_name, size))

        # Lookup struct
        out.write("// Initializer lookup by quality preset\n")
        out.write("struct InitializerBlob { const uint8_t* data; size_t size; };\n\n")
        out.write("static const InitializerBlob g_initializer_presets[] = {\n")
        for preset_name, size in sizes:
            out.write(f"    {{ g_initializer_{preset_name}_data, {size} }},  // {preset_name}\n")
        out.write("};\n\n")

        # Backward compat
        out.write("// Backward compatibility: default aliases\n")
        out.write(f"static const uint8_t* g_initializer_blob_data = g_initializer_performance_data;\n")
        out.write(f"static const size_t g_initializer_blob_size = {sizes[2][1]};\n")

    print(f"Generated {output_file}")
    for preset_name, size in sizes:
        print(f"  {preset_name}: {size:,} bytes ({size/1024:.1f} KB)")


def write_encoder1_header(shader_base: Path, output_file: Path):
    with open(output_file, "w") as out:
        out.write("// Auto-generated by scripts/embed_initializer.py -- do not edit, do not commit.\n")
        out.write("// Derived from AMD FidelityFX SDK FSR4 source (MIT License,\n")
        out.write("// Copyright (C) 2025 Advanced Micro Devices, Inc.). See LICENSE.\n")
        out.write("// Encoder1 conv weights for cbPass_Weights (b1), from each preset's pre.hlsl.\n")
        out.write("// Each array: 256 uint32_t = 1024 bytes.\n")
        out.write("#pragma once\n\n")
        out.write("#include <cstdint>\n\n")
        for preset_name, preset_dir in PRESETS:
            vals = read_encoder1_weights(shader_base / preset_dir / "pre.hlsl")
            out.write(f"// {preset_dir}/pre.hlsl\n")
            out.write(f"static const uint32_t weights_{preset_name}[256] = {{\n")
            for i in range(0, 256, 8):
                out.write("    " + ", ".join(vals[i:i+8]) + ",\n")
            out.write("};\n\n")
        out.write("// Weight lookup by quality preset index (matches FSR4QualityPreset)\n")
        out.write("static const uint32_t* encoder1_weights_by_preset[] = {\n")
        for preset_name, _ in PRESETS:
            out.write(f"    weights_{preset_name},\n")
        out.write("};\n")
    print(f"Generated {output_file}")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fsr4-source", type=Path, default=os.environ.get("FSR4_SOURCE"),
                        help="Root of your FidelityFX SDK / FSR4 source checkout "
                             "(default: $FSR4_SOURCE)")
    parser.add_argument("--out-dir", type=Path, default=REPO_ROOT / "src" / "dll",
                        help="Output directory for the generated headers (default: src/dll)")
    args = parser.parse_args()

    if not args.fsr4_source:
        parser.error("pass --fsr4-source or set FSR4_SOURCE")
    shader_base = Path(args.fsr4_source) / SHADER_SUBDIR
    if not shader_base.is_dir():
        sys.exit(f"ERROR: {shader_base} does not exist -- is --fsr4-source the SDK root?")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_initializer_header(shader_base, args.out_dir / "fsr4_initializer_blob.h")
    write_encoder1_header(shader_base, args.out_dir / "fsr4_encoder1_weights.h")


if __name__ == "__main__":
    main()
