#!/usr/bin/env python3
"""Convert compiled .cso shader files into a C++ header with embedded bytecode arrays.

Embeds four quality presets x three resolution tiers plus resolution-independent RCAS.
The pipeline selects the correct preset+tier at context creation based on scaling ratio
and upscale resolution.
"""

import os
import sys
from pathlib import Path

# Paths default to locations inside this repository. Override with:
#   python scripts/embed_shaders.py [shader_dir] [output_header]
_REPO_ROOT = Path(__file__).resolve().parent.parent
SHADER_DIR = sys.argv[1] if len(sys.argv) > 1 else str(_REPO_ROOT / "shaders" / "compiled")
OUTPUT_FILE = sys.argv[2] if len(sys.argv) > 2 else str(_REPO_ROOT / "src" / "dll" / "fsr4_shader_blobs.h")

PRESETS = ["quality", "balanced", "performance", "ultraperf"]
RESOLUTIONS = ["1080", "2160", "4320"]

def embed_blob(out, cso_path, var_name):
    """Read a CSO file and write it as a C++ byte array."""
    with open(cso_path, "rb") as f:
        data = f.read()

    size = len(data)
    name = os.path.basename(cso_path)
    out.write(f"// {name} ({size} bytes)\n")
    out.write(f"static const uint8_t {var_name}[] = {{\n")

    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        out.write(f"    {hex_str},\n")

    out.write(f"}};\n\n")
    return size


def main():
    total_bytes = 0

    with open(OUTPUT_FILE, "w") as out:
        out.write("// Auto-generated by scripts/embed_shaders.py -- do not edit, do not commit.\n")
        out.write("// Bytecode compiled from AMD FidelityFX SDK FSR4 shaders (MIT License,\n")
        out.write("// Copyright (C) 2025 Advanced Micro Devices, Inc.). See LICENSE.\n")
        out.write("// Contains shader bytecode for 4 quality presets x 3 resolution tiers + RCAS\n")
        out.write("#pragma once\n\n")
        out.write("#include <cstdint>\n\n")

        # RCAS (resolution-independent, quality-independent)
        rcas_path = os.path.join(SHADER_DIR, "rcas.cso")
        total_bytes += embed_blob(out, rcas_path, "g_shader_rcas")

        # Debug blend overlay (resolution-independent, quality-independent)
        overlay_path = os.path.join(SHADER_DIR, "debug_blend_overlay.cso")
        total_bytes += embed_blob(out, overlay_path, "g_shader_debug_blend_overlay")

        # Per-preset, per-resolution shaders
        for preset in PRESETS:
            for res in RESOLUTIONS:
                out.write(f"// ========== {preset} / {res}p ==========\n\n")

                # Pre shader
                pre_path = os.path.join(SHADER_DIR, f"pre_{preset}_{res}.cso")
                total_bytes += embed_blob(out, pre_path, f"g_shader_pre_{preset}_{res}")

                # Model passes 1-12
                for i in range(1, 13):
                    pass_path = os.path.join(SHADER_DIR, f"pass_{i}_{preset}_{res}.cso")
                    total_bytes += embed_blob(out, pass_path, f"g_shader_pass{i}_{preset}_{res}")

                # Post shader (fast_exp override)
                post_path = os.path.join(SHADER_DIR, f"post_{preset}_{res}.cso")
                total_bytes += embed_blob(out, post_path, f"g_shader_post_{preset}_{res}")

                # Post shader (normal/AMD original)
                post_normal_path = os.path.join(SHADER_DIR, f"post_normal_{preset}_{res}.cso")
                total_bytes += embed_blob(out, post_normal_path, f"g_shader_post_normal_{preset}_{res}")

                # Post shader (debug — FFX_DEBUG_VISUALIZE=1)
                post_debug_path = os.path.join(SHADER_DIR, f"post_debug_{preset}_{res}.cso")
                total_bytes += embed_blob(out, post_debug_path, f"g_shader_post_debug_{preset}_{res}")

        # Structs and enums
        out.write("// ========== Lookup tables ==========\n\n")
        out.write("struct ShaderBlob { const uint8_t* data; size_t size; };\n\n")
        out.write("// 14 shaders per tier: pre, pass1-12, post (fast_exp)\n")
        out.write("// + 1 alternate post (normal) per tier for A/B comparison\n")
        out.write("// RCAS is shared across all presets and tiers\n")
        out.write("static const int SHADERS_PER_TIER = 14;\n\n")

        # Quality preset enum
        out.write("enum FSR4QualityPreset {\n")
        out.write("    FSR4_PRESET_QUALITY = 0,\n")
        out.write("    FSR4_PRESET_BALANCED = 1,\n")
        out.write("    FSR4_PRESET_PERFORMANCE = 2,\n")
        out.write("    FSR4_PRESET_ULTRAPERF = 3,\n")
        out.write("    FSR4_PRESET_COUNT = 4,\n")
        out.write("};\n\n")

        # Resolution tier enum
        out.write("enum FSR4ResolutionTier {\n")
        out.write("    FSR4_RES_1080 = 0,\n")
        out.write("    FSR4_RES_2160 = 1,\n")
        out.write("    FSR4_RES_4320 = 2,\n")
        out.write("    FSR4_RES_COUNT = 3,\n")
        out.write("};\n\n")

        # Per-preset, per-resolution shader tables
        for preset in PRESETS:
            for res in RESOLUTIONS:
                out.write(f"static const ShaderBlob g_fsr4_{preset}_{res}[SHADERS_PER_TIER] = {{\n")
                out.write(f"    {{ g_shader_pre_{preset}_{res}, sizeof(g_shader_pre_{preset}_{res}) }},  // pre\n")
                for i in range(1, 13):
                    out.write(f"    {{ g_shader_pass{i}_{preset}_{res}, sizeof(g_shader_pass{i}_{preset}_{res}) }},  // pass{i}\n")
                out.write(f"    {{ g_shader_post_{preset}_{res}, sizeof(g_shader_post_{preset}_{res}) }},  // post\n")
                out.write(f"}};\n\n")

        # Master 2D table: [preset][resolution] -> ShaderBlob*
        out.write("// Master lookup: g_fsr4_presets[quality_preset][resolution_tier]\n")
        out.write("static const ShaderBlob* g_fsr4_presets[FSR4_PRESET_COUNT][FSR4_RES_COUNT] = {\n")
        for preset in PRESETS:
            out.write(f"    {{ // {preset}\n")
            for res in RESOLUTIONS:
                out.write(f"        g_fsr4_{preset}_{res},  // {res}p\n")
            out.write(f"    }},\n")
        out.write("};\n\n")

        # Normal Post blob lookup: [preset][resolution] -> ShaderBlob
        out.write("// Normal (AMD original) Post shader blobs for A/B comparison\n")
        out.write("static const ShaderBlob g_fsr4_post_normal[FSR4_PRESET_COUNT][FSR4_RES_COUNT] = {\n")
        for preset in PRESETS:
            out.write(f"    {{ // {preset}\n")
            for res in RESOLUTIONS:
                out.write(f"        {{ g_shader_post_normal_{preset}_{res}, sizeof(g_shader_post_normal_{preset}_{res}) }},  // {res}p\n")
            out.write(f"    }},\n")
        out.write("};\n\n")

        # Backward compat: g_fsr4_tiers points to performance preset (default)
        out.write("// Backward compatibility: default to performance preset\n")
        out.write("static const ShaderBlob** g_fsr4_tiers = g_fsr4_presets[FSR4_PRESET_PERFORMANCE];\n\n")

        # Debug Post blob lookup: [preset][resolution] -> ShaderBlob
        out.write("// Debug Post shader blobs (FFX_DEBUG_VISUALIZE=1, writes blend factor to u12)\n")
        out.write("static const ShaderBlob g_fsr4_post_debug[FSR4_PRESET_COUNT][FSR4_RES_COUNT] = {\n")
        for preset in PRESETS:
            out.write(f"    {{ // {preset}\n")
            for res in RESOLUTIONS:
                out.write(f"        {{ g_shader_post_debug_{preset}_{res}, sizeof(g_shader_post_debug_{preset}_{res}) }},  // {res}p\n")
            out.write(f"    }},\n")
        out.write("};\n\n")

        # RCAS blob (shared)
        out.write("static const ShaderBlob g_fsr4_rcas = {\n")
        out.write("    g_shader_rcas, sizeof(g_shader_rcas)\n")
        out.write("};\n\n")

        # Debug blend overlay blob (shared)
        out.write("// Debug blend factor overlay shader (reads t19, writes u2)\n")
        out.write("static const ShaderBlob g_fsr4_debug_overlay = {\n")
        out.write("    g_shader_debug_blend_overlay, sizeof(g_shader_debug_blend_overlay)\n")
        out.write("};\n")

    print(f"Generated {OUTPUT_FILE}")
    print(f"Total bytecode: {total_bytes:,} bytes ({total_bytes/1024:.1f} KB)")
    for preset in PRESETS:
        preset_size = 0
        for res in RESOLUTIONS:
            for name in [f"pre_{preset}_{res}"] + [f"pass_{i}_{preset}_{res}" for i in range(1, 13)] + [f"post_{preset}_{res}"]:
                path = os.path.join(SHADER_DIR, f"{name}.cso")
                if os.path.exists(path):
                    preset_size += os.path.getsize(path)
        print(f"  {preset}: {preset_size:,} bytes ({preset_size/1024:.1f} KB)")


if __name__ == "__main__":
    main()
